"""Synchronous events with a separate, non-serialised audio clip channel."""

from __future__ import annotations

from collections.abc import Callable, Mapping
from dataclasses import dataclass, field
from datetime import datetime, timezone
import math
from pathlib import Path
import sys
import threading
from typing import Any, TextIO

import numpy as np


def to_jsonable(value: Any) -> Any:
    """Return ordinary JSON types, including for NumPy-derived values.

    Non-finite measurements become null, rather than non-standard JSON NaN.
    Audio clips must be passed as ``_clip`` to ``EventBus.publish`` instead of
    being put in event data.
    """
    if isinstance(value, np.ndarray):
        return to_jsonable(value.tolist())
    if isinstance(value, np.generic):
        return to_jsonable(value.item())
    if value is None or isinstance(value, (str, bool, int)):
        return value
    if isinstance(value, float):
        return value if math.isfinite(value) else None
    if isinstance(value, Mapping):
        return {str(key): to_jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [to_jsonable(item) for item in value]
    if isinstance(value, Path):
        return str(value)
    # Error details may include exception objects or device-specific values.
    return str(value)


def _wall_time() -> str:
    return datetime.now(timezone.utc).isoformat()


@dataclass
class Event:
    type: str
    t: float
    wall: str = field(default_factory=_wall_time)
    data: dict[str, Any] = field(default_factory=dict)
    _clip: np.ndarray | None = field(default=None, repr=False, compare=False)

    @property
    def clip(self) -> np.ndarray | None:
        """The optional audio side channel; excluded from ``to_dict``."""
        return self._clip

    def to_dict(self) -> dict[str, Any]:
        return to_jsonable(
            {"type": self.type, "t": self.t, "wall": self.wall, "data": self.data}
        )


Subscriber = Callable[[Event], None]


class EventBus:
    """Serialize publication and isolate failed subscribers.

    The reentrant lock permits a subscriber to publish another event. Errors
    generated by a failed subscriber are delivered directly, with any further
    subscriber failures suppressed, so error reporting cannot recurse forever.
    """

    def __init__(self) -> None:
        self._subscribers: list[Subscriber] = []
        self._lock = threading.RLock()

    def subscribe(self, callback: Subscriber) -> Callable[[], None]:
        with self._lock:
            self._subscribers.append(callback)
        return lambda: self.unsubscribe(callback)

    def unsubscribe(self, callback: Subscriber) -> None:
        with self._lock:
            if callback in self._subscribers:
                self._subscribers.remove(callback)

    def publish(self, type: str, t: float, **data: Any) -> Event:
        clip = data.pop("_clip", None)
        event = Event(type=type, t=float(t), data=to_jsonable(data), _clip=clip)
        with self._lock:
            subscribers = tuple(self._subscribers)
            failures: list[tuple[Subscriber, Exception]] = []
            for callback in subscribers:
                try:
                    callback(event)
                except Exception as exc:
                    failures.append((callback, exc))
            for failed, exc in failures:
                error = Event(
                    type="error",
                    t=event.t,
                    data={
                        "source": "event_bus",
                        "message": f"Subscriber failed: {exc}",
                        "subscriber": getattr(failed, "__name__", type_name(failed)),
                        "event_type": event.type,
                    },
                )
                for callback in subscribers:
                    if callback is failed:
                        continue
                    try:
                        callback(error)
                    except Exception:
                        pass
        return event


def type_name(value: Any) -> str:
    return value.__class__.__name__


class ConsoleSink:
    """A small human-readable sink; callers may filter event types first."""

    def __init__(self, stream: TextIO | None = None) -> None:
        self.stream = stream if stream is not None else sys.stdout

    def __call__(self, event: Event) -> None:
        data = event.data
        if event.type == "sound":
            label = "KNOCK" if data.get("is_knock") else "SOUND"
            line = (
                f"{event.t:.2f}s  {label}  snr {data.get('snr_db', 0):.1f} dB  "
                f"peak {data.get('peak', 0):.2f}  ({data.get('classifier', 'none')})"
            )
            if data.get("gated"):
                line += " [gated]"
            if (data.get("gated") or not data.get("is_knock")) and getattr(
                self.stream, "isatty", lambda: False
            )():
                line = f"\033[2m{line}\033[0m"
        elif event.type == "level":
            line = f"{event.t:.2f}s  level {data.get('dbfs', 0):.1f} dBFS"
        elif event.type == "error":
            line = f"{event.t:.2f}s  {data.get('severity', 'error').upper()}: {data.get('message', data)}"
        else:
            line = f"{event.t:.2f}s  {event.type}  {data}"
        print(line, file=self.stream, flush=True)
